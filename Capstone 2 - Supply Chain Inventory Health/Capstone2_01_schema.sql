CREATE TABLE dbo.Dim_Supplier (
    SupplierID    INT           NOT NULL PRIMARY KEY,
    SupplierName  NVARCHAR(100) NOT NULL,
    LeadTimeDays  INT           NOT NULL
);
GO

CREATE TABLE dbo.Dim_Product (
    ProductID     INT            NOT NULL PRIMARY KEY,
    ProductName   NVARCHAR(100)  NOT NULL,
    Category      NVARCHAR(50)   NOT NULL,
    UnitCostNGN   DECIMAL(10,2)  NOT NULL,
    SupplierID    INT            NOT NULL,
    CONSTRAINT FK_Product_Supplier FOREIGN KEY (SupplierID) REFERENCES dbo.Dim_Supplier(SupplierID)
);
GO

CREATE TABLE dbo.Dim_Warehouse (
    WarehouseID   INT            NOT NULL PRIMARY KEY,
    WarehouseName NVARCHAR(50)   NOT NULL,
    Region        NVARCHAR(50)   NOT NULL
);
GO

CREATE TABLE dbo.Fact_Sales (
    WeekStart     DATE  NOT NULL,
    WarehouseID   INT   NOT NULL,
    ProductID     INT   NOT NULL,
    UnitsSold     INT   NOT NULL,
    CONSTRAINT FK_Sales_Warehouse FOREIGN KEY (WarehouseID) REFERENCES dbo.Dim_Warehouse(WarehouseID),
    CONSTRAINT FK_Sales_Product FOREIGN KEY (ProductID) REFERENCES dbo.Dim_Product(ProductID)
);
GO

CREATE TABLE dbo.Fact_Inventory (
    WarehouseID   INT            NOT NULL,
    ProductID     INT            NOT NULL,
    CurrentStock  INT            NOT NULL,
    SnapshotDate  DATE           NOT NULL,
    CONSTRAINT PK_Fact_Inventory PRIMARY KEY (WarehouseID, ProductID),
    CONSTRAINT FK_Inv_Warehouse FOREIGN KEY (WarehouseID) REFERENCES dbo.Dim_Warehouse(WarehouseID),
    CONSTRAINT FK_Inv_Product FOREIGN KEY (ProductID) REFERENCES dbo.Dim_Product(ProductID)
);
GO

